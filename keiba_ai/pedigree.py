"""血統適性。

阪神芝2000m「内回り」= スタート直後に1角、コーナー4つ、直線356m。
瞬発力一辺倒より、コーナーでの加速と持続力・パワーが要る。
さらに今回は火〜金の降雨(89mm)で含水率が高め残りのため、
軽い高速馬場専用のスピード型より、力の要る馬場をこなす血統を上に取る。

スコアは 5.0 を中立とした 0-10 のレンジ。
"""
from __future__ import annotations

# 父系: 阪神芝2000内回り適性
SIRE_APTITUDE = {
    "ドゥラメンテ": 7.5,       # キンカメ系。阪神芝2000は最も得意な条件のひとつ
    "ルーラーシップ": 7.2,     # 小回り・内回りの立ち回りに強いキンカメ系
    "キタサンブラック": 7.0,   # 持続力型。中距離の消耗戦に強い
    "エピファネイア": 6.6,     # ロベルト系のパワー。阪神芝2000の好相性
    "キズナ": 6.5,             # 関西圏中距離。渋った馬場もこなす
    "サートゥルナーリア": 6.0,
    "リアルスティール": 5.6,
    "レイデオロ": 5.5,
    "ヤマカツエース": 5.2,
    "モーリス": 5.0,           # 本質はマイル〜1800
    "グレーターロンドン": 4.9, # 軽い芝のスピード型。タフな馬場は割引
    "グランデッツァ": 4.5,
}

# 母父: 補完要素(スタミナ・パワー・底力)
BMS_APTITUDE = {
    "ハーツクライ": 6.2,
    "ハービンジャー": 6.1,
    "キングカメハメハ": 6.0,
    "オルフェーヴル": 6.0,
    "Candy Ride": 6.0,
    "マンハッタンカフェ": 5.7,
    "ジャングルポケット": 5.6,
    "Machiavellian": 5.5,
    "スペシャルウィーク": 5.5,
    "ロードカナロア": 5.4,
    "Concorde's Tune": 5.4,
    "Burning Roma": 5.0,
    "Footstepsinthesand": 4.8,
    "Global Hunter": 4.9,
}

# 湿った馬場・力の要る馬場への対応力(父系)
WET_TOLERANCE = {
    "ドゥラメンテ": 0.4,
    "キタサンブラック": 0.5,
    "エピファネイア": 0.5,
    "ルーラーシップ": 0.4,
    "キズナ": 0.3,
    "グレーターロンドン": -0.4,
    "モーリス": -0.1,
}

NEUTRAL = 5.0


def pedigree_score(sire: str, bms: str, moisture: float | None) -> tuple[float, str]:
    """血統適性を指数ポイント(概ね ±2.5)で返す。"""
    s = SIRE_APTITUDE.get(sire, NEUTRAL)
    b = BMS_APTITUDE.get(bms, NEUTRAL)
    raw = 0.65 * s + 0.35 * b - NEUTRAL
    pts = raw * 0.95

    # 含水率が高い(=力の要る馬場)ほど、タフな馬場適性の差が出る
    if moisture is not None and moisture >= 14.0:
        weight = min((moisture - 14.0) / 4.0, 1.0)
        pts += WET_TOLERANCE.get(sire, 0.0) * weight * 2.0

    detail = f"父{sire}({s:.1f}) 母父{bms}({b:.1f})"
    return pts, detail
