"""走破タイムとラップ(上がり3F・通過順)による評価軸。

着差ベースの指数だけだと「速い決着の凡走」と「遅い決着の好走」を区別できない。
実際このレースでは、マリアイリダータの前走(3勝クラス)が
福島芝2000のコースレコード 1:56.7 だったことを着差モデルは全く評価できていなかった。

ここでは2つの軸を足す。
  1. 速度指数 : 会場・距離ごとの基準タイムと自身の走破タイムの差
  2. ラップ補正: 上がり3F を「どの位置から使ったか」で重み付けする
"""
from __future__ import annotations

import math

from .models import PastRun


def _saturate(x: float, cap: float) -> float:
    """tanh で滑らかに飽和させる。極端値を潰しつつ大小関係は保たれる。"""
    return cap * math.tanh(x / cap)

# ---------------------------------------------------------------- 基準タイム
# 良馬場・G3(重賞オープン)水準の勝ちタイム(秒)。
# 一般的な「基準タイム表」ではなく、本レースの出走馬が2025-26年に実際に走った
# レースの勝ちタイムから逆算して置いている(例: 小倉芝2000 は小倉記念 1:58.0、
# 関門橋S 2:00.3、小倉日経OP 1:59.4 から 118.3 秒)。
# 出典が同一シーズンなので、教科書的な基準タイムより現在の馬場に近い。
STANDARD_TIMES = {
    "阪神芝2000": 117.8, "阪神芝1800外": 104.8, "阪神芝2200": 131.5,
    "阪神芝2400外": 143.2, "阪神芝2600外": 157.0,
    "中山芝2000": 118.8, "中山芝1800": 106.3, "中山芝2200外": 131.5,
    "中山芝2200": 131.8, "中山芝2500": 151.0,
    "東京芝2000": 117.5, "東京芝1800": 105.3, "東京芝2400": 143.0,
    "京都芝2000": 118.5, "京都芝1800外": 104.5, "京都芝1600外": 93.0,
    "京都芝3000外": 184.0, "京都芝3200外": 193.7,
    "中京芝2000": 118.2, "中京芝2200": 130.5,
    "小倉芝2000": 118.3, "小倉芝1800": 105.8,
    "福島芝2000": 118.2, "福島芝1800": 106.3,
    "函館芝2000": 118.2,
    "新潟芝2000外": 118.3, "新潟芝1600外": 92.5,
}

# クラスごとに、そのレースで出て当然のタイム差(秒)。正=遅くて当然。
# 条件戦でも流れが速ければ重賞並みの時計は普通に出るので、差は控えめに取る。
CLASS_TIME_ADJ = {
    "G1": -0.5, "G2": -0.25, "G3": 0.0, "L": 0.2, "OP": 0.35,
    "3勝": 0.6, "2勝": 1.1, "1勝": 1.7, "未勝利": 2.4,
}

# 馬場状態による時計の掛かり(秒)。正=時計を要するので加点方向。
GOING_TIME_ADJ = {"良": 0.0, "稍": 0.5, "重": 1.0, "不": 1.5}

# 速度指数の中心(=基準どおりのタイムで走ったときの値)。G3水準に合わせる。
SPEED_CENTER = 96.0
# 絶対タイムは日々の馬場差というノイズを含むため、着差より換算率を抑える。
SPEED_SEC_TO_POINTS = 5.0
# ハードな打ち切りではなく tanh で滑らかに飽和させる。
# 打ち切りにすると「コースレコード」と「条件戦の好時計」が同点になり順序が壊れる。
SPEED_CAP = 10.0

# ---------------------------------------------------------------- ラップ補正
# 良馬場・G3水準の上がり3F(秒)
REF_LAST3F = {
    1600: 34.0, 1700: 34.2, 1800: 34.4, 2000: 34.8, 2100: 34.9,
    2200: 35.0, 2400: 35.0, 2500: 35.2, 2600: 35.3, 3000: 35.6, 3200: 35.8,
}
# 上がり3F はクラスが下がるほど遅くなる、のではない。
# 下級条件戦はペースが緩みやすく、むしろ上がりは速く出る。符号に注意。
CLASS_LAST3F_ADJ = {
    "G1": 0.15, "G2": 0.1, "G3": 0.0, "L": 0.0, "OP": 0.0,
    "3勝": -0.05, "2勝": -0.1, "1勝": -0.15, "未勝利": -0.2,
}
LAP_SCALE = 4.0
LAP_CAP = 2.0


def speed_rating(run: PastRun) -> tuple[float | None, str]:
    """走破タイムから速度指数を出す。タイムか基準タイムが無ければ None。"""
    if run.time is None or run.track is None:
        return None, "タイム欠測"
    base = STANDARD_TIMES.get(run.track)
    if base is None:
        return None, f"基準タイム未登録({run.track})"

    expected = base + CLASS_TIME_ADJ.get(run.grade, 0.0) + GOING_TIME_ADJ.get(run.going, 0.0)
    diff = expected - run.time                      # 正 = 基準より速い
    diff2000 = diff * (2000.0 / run.distance)       # 2000m 換算
    pts = _saturate(diff2000 * SPEED_SEC_TO_POINTS, SPEED_CAP)
    detail = f"{run.track} 想定{expected:.1f}秒 vs 実走{run.time:.1f}秒 ({diff2000:+.2f}秒)"
    return SPEED_CENTER + pts, detail


def lap_adjustment(run: PastRun) -> float:
    """上がり3F を「どの位置から使ったか」で重み付けした持続力の補正。

    最後方から上がり最速を出すのは展開利で起こりうるが、
    前めの位置で速い上がりを使うのは純粋に強い。前者を割り引き後者を評価する。
    """
    if run.last3f is None:
        return 0.0
    ref = REF_LAST3F.get(run.distance)
    if ref is None:
        return 0.0
    ref += CLASS_LAST3F_ADJ.get(run.grade, 0.0) + GOING_TIME_ADJ.get(run.going, 0.0)
    credit = ref - run.last3f                       # 正 = 基準より速い上がり

    if run.passes and run.field_size > 1:
        avg_pos = sum(run.passes) / len(run.passes)
        # 先頭=0, 最後方=1 に正規化(少頭数で前めに見えすぎるのを防ぐ)
        back = min(max((avg_pos - 1.0) / (run.field_size - 1.0), 0.0), 1.0)
        front = 1.0 - back
    else:
        front = 0.5
    # 前めの位置で速い上がりを使った方を高く評価する
    return _saturate(credit * LAP_SCALE * (0.45 + 0.55 * front), LAP_CAP)
